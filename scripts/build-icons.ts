interface IconSet {
  prefix: string;
  width?: number;
  height?: number;
  icons: Record<string, { body: string; width?: number; height?: number }>;
  aliases?: Record<string, { parent: string }>;
  info?: { name: string; author?: { name: string; url?: string }; license?: { title: string } };
}

const sets = new Map<string, IconSet>();
async function load(prefix: string): Promise<IconSet> {
  if (!sets.has(prefix)) {
    const icons = (await import(`@iconify-json/${prefix}/icons.json`, { with: { type: "json" } })).default;
    const info = (await import(`@iconify-json/${prefix}/info.json`, { with: { type: "json" } })).default;
    sets.set(prefix, { ...icons, info });
  }
  return sets.get(prefix)!;
}

const out: Record<string, { body: string; width: number; height: number }> = {};
for (const [name, ref] of Object.entries(ICONS)) {
  const [prefix, iconName] = ref.split(":");
  const set = await load(prefix);
  const resolved = set.icons[iconName] ?? set.icons[set.aliases?.[iconName]?.parent ?? ""];
  if (!resolved) throw new Error(`Icon not found: ${ref}`);
  out[name] = {
    body: resolved.body,
    width: resolved.width ?? set.width ?? 16,
    height: resolved.height ?? set.height ?? 16,
  };
}

const credits = [...new Set(Object.values(ICONS).map((r) => r.split(":")[0]))]
  .map((p) => {
    const info = sets.get(p)?.info;
    return ` * ${info?.name ?? p} by ${info?.author?.name ?? "unknown"}, ${info?.license?.title ?? "see package"}: ${info?.author?.url ?? ""}`;
  })
  .join("\n");

writeFileSync(
  "src/components/icon/data.ts",
  `/**
 * Generated by scripts/build-icons.ts. Do not edit; change ICONS there.
${credits}
 */
export const ICONS = ${JSON.stringify(out, null, 2)} as const;

export type IconName = keyof typeof ICONS;
`,
);
console.log(`wrote ${Object.keys(out).length} icons`);
